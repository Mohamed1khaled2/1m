const WEEK = 7 * 86_400_000;

/** أول يوم في أسبوع الحلقة: الحلقة بتفتح فيه. */
export function weekStart(year: number, q: number, week: number): Date {
  return new Date(Date.UTC(year, (q - 1) * 3, 1) + (week - 1) * WEEK);
}

/** إحنا في أنهي أسبوع من الربع (من ١)، و٠ لو الربع لسه مابدأش. */
export function weekOfQuarter(year: number, q: number, at: Date): number {
  const start = Date.UTC(year, (q - 1) * 3, 1);
  return at.getTime() < start ? 0 : Math.floor((at.getTime() - start) / WEEK) + 1;
}

